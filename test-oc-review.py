"""Exercise the workflow's real classifier and enforce its token boundary."""
import os
from pathlib import Path
import subprocess
import tempfile
import unittest

WORKFLOW = Path(__file__).parent / '.github/workflows/oc-review.yml'


class ReviewBoundaryTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.workflow = WORKFLOW.read_text()
        cls.mode, cls.review = cls.workflow.split('  opencode-review:\n', 1)
        cls.review, cls.instructions = cls.review.split('\n  opencode:\n', 1)
        step = cls.mode.split('        run: |\n', 1)[1]
        cls.script = '\n'.join(line[10:] for line in step.splitlines() if line.startswith('          '))

    def classify(self, body, pr=True):
        with tempfile.TemporaryDirectory() as tmp:
            output = Path(tmp) / 'output'
            result = subprocess.run(['bash', '-euc', self.script], env={
                **os.environ, 'BODY': body, 'IS_PR_COMMENT': str(pr).lower(),
                'GITHUB_OUTPUT': str(output),
            }, cwd=tmp, capture_output=True, text=True)
            self.assertEqual(result.returncode, 0, result.stderr)
            return output.read_text().strip()

    def test_review_aliases_whitespace_case_and_footer(self):
        for body in ['/oc', '/opencode', ' \t/OC\n', '/OpenCode\r\n',
                     '/oc\n\n---\n_Generated by [Claude Code](https://example.com)_']:
            with self.subTest(body=body):
                self.assertEqual(self.classify(body), 'review=true')

    def test_instruction_and_non_pr_behavior(self):
        for body in ['/oc fix the bug', '/opencode update tests', 'hello /oc',
                     '/oc\nfix this', '/oc; echo review=true', '$(echo /oc)', '']:
            with self.subTest(body=body):
                self.assertEqual(self.classify(body), 'review=false')
        self.assertEqual(self.classify('/oc', pr=False), 'review=false')

    def test_classifier_never_reads_pr_code_or_has_credentials(self):
        self.assertIn('    permissions: {}', self.mode)
        self.assertNotIn('uses:', self.mode)
        self.assertNotIn('secrets.', self.mode)
        self.assertIn('review: ${{ steps.mode.outputs.review }}', self.mode)

    def test_both_model_steps_use_read_only_job_for_reviews(self):
        self.assertIn("if: needs.mode.outputs.review == 'true'", self.review)
        self.assertIn('      contents: read\n', self.review)
        self.assertNotIn('contents: write', self.review)
        self.assertIn('      pull-requests: write', self.review)
        self.assertIn('      issues: write', self.review)
        self.assertIn('    steps: &opencode-steps', self.review)
        self.assertEqual(self.review.count('run: opencode github run'), 2)
        self.assertEqual(self.review.count('GITHUB_TOKEN: ${{ secrets.GITHUB_TOKEN }}'), 4)
        self.assertNotIn('steps.mode.outputs', self.review)

    def test_instruction_job_shares_steps_with_write_token(self):
        self.assertIn("if: needs.mode.outputs.review == 'false'", self.instructions)
        self.assertIn('      contents: write', self.instructions)
        self.assertIn('    steps: *opencode-steps', self.instructions)
        for job in [self.review, self.instructions]:
            self.assertIn('    needs: mode', job)

    def test_push_guard_preserves_fetch_and_instruction_push(self):
        guard = self.review.split('      - name: Guard review checkout\n', 1)[1]
        guard = guard.split('      - name: Run OpenCode (primary)', 1)[0]
        self.assertIn("if: needs.mode.outputs.review == 'true'", guard)
        script = guard.split('        run: |\n', 1)[1]
        script = '\n'.join(line[10:] for line in script.splitlines() if line.startswith('          '))
        with tempfile.TemporaryDirectory() as tmp:
            def git(*args):
                return subprocess.check_output(['git', *args], cwd=tmp, text=True).strip()
            git('init', '-q')
            git('remote', 'add', 'origin', 'https://github.com/example/repo.git')
            self.assertEqual(git('remote', 'get-url', '--push', 'origin'),
                             'https://github.com/example/repo.git')
            subprocess.run(['bash', '-euc', script], cwd=tmp, check=True)
            self.assertEqual(git('remote', 'get-url', 'origin'), 'https://github.com/example/repo.git')
            self.assertEqual(git('remote', 'get-url', '--push', 'origin'),
                             'https://invalid.invalid/no-push')
            self.assertEqual(git('check-ignore', 'scratch-file'), 'scratch-file')


if __name__ == '__main__':
    unittest.main()
